import { EventEmitter } from 'node:events';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import puppeteer from 'puppeteer-core';

const SITE_CONFIG = {
  bilibili: {
    loginUrl: 'https://passport.bilibili.com/login',
    accountUrl: 'https://api.bilibili.com/x/web-interface/nav',
    cookieUrls: [
      'https://www.bilibili.com',
      'https://api.bilibili.com',
      'https://passport.bilibili.com',
      'https://www.bilivideo.com',
    ],
    async readAccount(page) {
      const payload = JSON.parse(await page.evaluate(() => document.body.innerText));
      const data = payload.data || {};
      const loggedIn = Boolean(data.isLogin && data.uname);
      return {
        loggedIn,
        username: loggedIn ? data.uname : null,
        vipLabel: loggedIn ? (data.vipStatus === 1 ? (data.vipType === 2 ? '年度大会员' : '大会员') : '普通账号') : null,
        cookies: await page.cookies(...SITE_CONFIG.bilibili.cookieUrls),
      };
    },
  },
  xiaohongshu: {
    loginUrl: 'https://www.xiaohongshu.com/login',
    accountUrl: 'https://www.xiaohongshu.com',
    cookieUrls: [
      'https://www.xiaohongshu.com',
      'https://edith.xiaohongshu.com',
      'https://www.xiaohongshu.com/discovery/item',
    ],
    async readAccount(page) {
      const cookies = await page.cookies(...SITE_CONFIG.xiaohongshu.cookieUrls);
      const loggedIn = cookies.some((cookie) => cookie.name === 'web_session' && cookie.value);
      return {
        loggedIn,
        username: loggedIn ? '小红书账号' : null,
        vipLabel: loggedIn ? '已登录账号' : null,
        cookies,
      };
    },
  },
};

function fromPath(name) {
  for (const directory of (process.env.PATH || '').split(path.delimiter)) {
    const candidate = path.join(directory, name);
    try {
      fs.accessSync(candidate, fs.constants.X_OK);
      return candidate;
    } catch {}
  }
  return null;
}

export function chromeExecutable() {
  const candidates = [];
  if (process.env.CHROME_PATH) candidates.push(process.env.CHROME_PATH);
  if (process.platform === 'darwin') {
    candidates.push(
      '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
      '/Applications/Chromium.app/Contents/MacOS/Chromium',
      '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
      path.join(os.homedir(), 'Applications/Google Chrome.app/Contents/MacOS/Google Chrome'),
    );
  } else if (process.platform === 'win32') {
    for (const root of [process.env.PROGRAMFILES, process.env['PROGRAMFILES(X86)'], process.env.LOCALAPPDATA].filter(Boolean)) {
      candidates.push(path.join(root, 'Google/Chrome/Application/chrome.exe'), path.join(root, 'Chromium/Application/chrome.exe'));
    }
  } else {
    candidates.push('/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser');
  }
  for (const candidate of candidates) {
    try {
      fs.accessSync(candidate, fs.constants.X_OK);
      return candidate;
    } catch {}
  }
  return process.platform === 'win32' ? fromPath('chrome.exe') : fromPath('google-chrome') || fromPath('chromium');
}

export function netscapeCookies(cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Downbit Local. Do not share this file.'];
  for (const cookie of cookies) {
    if (!cookie.name || !cookie.domain) continue;
    const domain = cookie.httpOnly ? `#HttpOnly_${cookie.domain}` : cookie.domain;
    const includeSubdomains = cookie.domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const cookiePath = cookie.path || '/';
    const secure = cookie.secure ? 'TRUE' : 'FALSE';
    const expires = Number.isFinite(cookie.expires) && cookie.expires > 0 ? Math.floor(cookie.expires) : 0;
    const value = String(cookie.value ?? '').replace(/[\t\r\n]/g, '');
    lines.push([domain, includeSubdomains, cookiePath, secure, expires, cookie.name, value].join('\t'));
  }
  return `${lines.join('\n')}\n`;
}

export class AccountManager extends EventEmitter {
  constructor(dataDir, site = 'bilibili') {
    super();
    this.site = site;
    this.config = SITE_CONFIG[site];
    if (!this.config) throw new Error(`不支持的账号站点：${site}`);
    this.cookieFile = path.join(dataDir, 'cookies', `${site}.txt`);
    this.profileDir = site === 'bilibili' ? path.join(dataDir, 'browser-profile') : path.join(dataDir, `browser-profile-${site}`);
    this.statusFile = path.join(dataDir, `${site}-account.json`);
    this.browser = null;
    this.page = null;
    this.launching = null;
    this.refreshing = null;
    this.loginTimer = null;
    this.awaitingLogin = false;
    this.status = { loggedIn: false, username: null, vipLabel: null, updatedAt: null };
    try {
      const saved = JSON.parse(fs.readFileSync(this.statusFile, 'utf8'));
      if (fs.existsSync(this.cookieFile)) this.status = { ...this.status, ...saved };
    } catch {}
  }

  snapshot() {
    return {
      available: Boolean(chromeExecutable()),
      awaitingLogin: this.awaitingLogin,
      ...this.status,
    };
  }

  save() {
    fs.mkdirSync(path.dirname(this.statusFile), { recursive: true });
    fs.writeFileSync(this.statusFile, JSON.stringify(this.status, null, 2), { mode: 0o600 });
    this.emit('change', this.snapshot());
  }

  cookiePath() {
    return this.status.loggedIn && fs.existsSync(this.cookieFile) ? this.cookieFile : null;
  }

  async ensureBrowser(headless = false) {
    if (this.browser?.connected) return this.browser;
    if (this.launching) return this.launching;
    this.launching = (async () => {
      const executablePath = chromeExecutable();
      if (!executablePath) throw new Error('没有找到 Chrome。请安装 Chrome，或设置 CHROME_PATH 后重试。');
      fs.mkdirSync(this.profileDir, { recursive: true, mode: 0o700 });
      const browser = await puppeteer.launch({
        executablePath,
        headless,
        pipe: true,
        userDataDir: this.profileDir,
        defaultViewport: null,
        args: ['--no-first-run', '--no-default-browser-check'],
      });
      this.browser = browser;
      browser.on('disconnected', () => {
        this.browser = null;
        this.page = null;
        this.awaitingLogin = false;
        if (this.loginTimer) clearInterval(this.loginTimer);
        this.loginTimer = null;
        this.emit('change', this.snapshot());
      });
      return browser;
    })();
    try {
      return await this.launching;
    } finally {
      this.launching = null;
    }
  }

  async login() {
    const browser = await this.ensureBrowser(false);
    const pages = await browser.pages();
    this.page = pages.find((page) => page.url().includes(this.site === 'bilibili' ? 'bilibili.com' : 'xiaohongshu.com')) || await browser.newPage();
    await this.page.bringToFront();
    await this.page.goto(this.config.loginUrl, { waitUntil: 'domcontentloaded', timeout: 60000 });
    this.awaitingLogin = true;
    this.save();
    if (this.loginTimer) clearInterval(this.loginTimer);
    this.loginTimer = setInterval(async () => {
      try {
        const status = await this.refresh();
        if (status.loggedIn) {
          if (this.loginTimer) clearInterval(this.loginTimer);
          this.loginTimer = null;
          this.awaitingLogin = false;
          await this.closeBrowser();
          this.save();
        }
      } catch {}
    }, 4000);
    return { ...this.snapshot(), loginUrl: this.page.url() };
  }

  async refresh() {
    if (this.refreshing) return this.refreshing;
    this.refreshing = (async () => {
      if (!this.browser && !fs.existsSync(this.cookieFile) && !fs.existsSync(this.profileDir)) return this.snapshot();
      const browser = await this.ensureBrowser(true);
      const page = await browser.newPage();
      try {
        await page.goto(this.config.accountUrl, { waitUntil: 'domcontentloaded', timeout: 60000 });
        const account = await this.config.readAccount(page);
        const loggedIn = account.loggedIn;
        if (loggedIn) {
          fs.mkdirSync(path.dirname(this.cookieFile), { recursive: true, mode: 0o700 });
          fs.writeFileSync(this.cookieFile, netscapeCookies(account.cookies), { mode: 0o600 });
          this.status = {
            loggedIn: true,
            username: account.username,
            vipLabel: account.vipLabel,
            updatedAt: new Date().toISOString(),
          };
          this.awaitingLogin = false;
          this.save();
        } else if (this.status.loggedIn || fs.existsSync(this.cookieFile)) {
          this.status = { loggedIn: false, username: null, vipLabel: null, updatedAt: new Date().toISOString() };
          await fs.promises.rm(this.cookieFile, { force: true });
          this.save();
        }
        return this.snapshot();
      } finally {
        await page.close();
      }
    })();
    try {
      return await this.refreshing;
    } finally {
      this.refreshing = null;
    }
  }

  async logout() {
    if (this.loginTimer) clearInterval(this.loginTimer);
    this.loginTimer = null;
    this.awaitingLogin = false;
    if (this.browser || fs.existsSync(this.profileDir)) {
      const browser = await this.ensureBrowser(true);
      const pages = await browser.pages();
      const page = pages[0] || await this.browser.newPage();
      const cookies = await page.cookies(...this.config.cookieUrls);
      if (cookies.length) await page.deleteCookie(...cookies);
    }
    await this.closeBrowser();
    await fs.promises.rm(this.cookieFile, { force: true });
    this.status = { loggedIn: false, username: null, vipLabel: null, updatedAt: new Date().toISOString() };
    this.save();
    return this.snapshot();
  }

  async closeBrowser() {
    if (this.browser?.connected) await this.browser.close();
    this.browser = null;
    this.page = null;
  }

  async close() {
    if (this.loginTimer) clearInterval(this.loginTimer);
    this.loginTimer = null;
    await this.closeBrowser();
  }
}
